import { constants as fsConstants } from "node:fs";
import { access, copyFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";

function requireText(value, name) {
  const normalized = String(value || "").trim();
  if (!normalized) throw new Error(`${name} is required.`);
  return normalized;
}

function powerShellLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function positiveInteger(value, name) {
  const normalized = Number(value);
  if (!Number.isSafeInteger(normalized) || normalized < 1) {
    throw new Error(`${name} must be a positive integer.`);
  }
  return normalized;
}

export function supervisorMutexName(taskName) {
  const digest = createHash("sha256").update(requireText(taskName, "taskName")).digest("hex").slice(0, 16);
  return `Local\\CodexUsageMesh-${digest}`;
}

export function generateWindowsSupervisor({
  repoRoot,
  statePath,
  nodePath,
  logPath,
  headlessHostPath,
  taskName = "CodexUsageMesh",
  restartDelaySeconds = 30,
  projectMode = "hash",
  includeTitles = false,
} = {}) {
  const normalizedRepoRoot = path.resolve(requireText(repoRoot, "repoRoot"));
  const normalizedStatePath = path.resolve(requireText(statePath, "statePath"));
  const normalizedNodePath = path.resolve(requireText(nodePath, "nodePath"));
  const normalizedLogPath = path.resolve(requireText(logPath, "logPath"));
  const normalizedDelay = positiveInteger(restartDelaySeconds, "restartDelaySeconds");
  const normalizedProjectMode = String(projectMode || "hash").toLowerCase();
  if (!new Set(["hash", "basename", "full"]).has(normalizedProjectMode)) {
    throw new Error("projectMode must be hash, basename, or full.");
  }

  const values = {
    repoRoot: powerShellLiteral(normalizedRepoRoot),
    statePath: powerShellLiteral(normalizedStatePath),
    nodePath: powerShellLiteral(normalizedNodePath),
    logPath: powerShellLiteral(normalizedLogPath),
    headlessHostPath: powerShellLiteral(path.resolve(headlessHostPath || path.join(normalizedRepoRoot, ".cache", "windows-agent", `${taskName}.Host.exe`))),
    mutexName: powerShellLiteral(supervisorMutexName(taskName)),
    projectMode: powerShellLiteral(normalizedProjectMode),
    includeTitles: includeTitles ? "'true'" : "'false'",
    delay: normalizedDelay,
  };

  return `# Generated by scripts/windows/Install-CodexUsageMesh.ps1. Do not add secrets here.
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$RepoRoot = ${values.repoRoot}
$StatePath = ${values.statePath}
$NodePath = ${values.nodePath}
$LogPath = ${values.logPath}
$HeadlessHostPath = ${values.headlessHostPath}
$AgentPath = Join-Path $RepoRoot 'agent.mjs'
$MutexName = ${values.mutexName}
$RestartDelaySeconds = ${values.delay}
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
try { [Console]::OutputEncoding = $Utf8NoBom } catch {}
$OutputEncoding = $Utf8NoBom

function Write-SupervisorLog {
    param([Parameter(Mandatory = $true)][string]$Message)
    $ErrorActionPreference = 'Stop'
    $directory = Split-Path -Parent $LogPath
    if ($directory) { [System.IO.Directory]::CreateDirectory($directory) | Out-Null }
    $timestamp = [DateTimeOffset]::Now.ToString('yyyy-MM-ddTHH:mm:ss.fffzzz')
    [System.IO.File]::AppendAllText($LogPath, "[$timestamp] $Message" + [Environment]::NewLine, $Utf8NoBom)
}

function Invoke-AgentProcess {
    return [CodexUsageMesh.HeadlessProcess]::Run($NodePath, [string[]]@($AgentPath, '--state-path', $StatePath), $RepoRoot, $LogPath, 'agent')
}

$mutex = $null
$ownsMutex = $false
try {
    $mutex = New-Object System.Threading.Mutex($false, $MutexName)
    try {
        $ownsMutex = $mutex.WaitOne(0, $false)
    } catch [System.Threading.AbandonedMutexException] {
        $ownsMutex = $true
    }
    if (-not $ownsMutex) {
        Write-SupervisorLog 'supervisor duplicate ignored; another instance owns the mutex'
        exit 0
    }

    if (-not (Test-Path -LiteralPath $NodePath -PathType Leaf)) { throw "Node.js introuvable : $NodePath" }
    if (-not (Test-Path -LiteralPath $AgentPath -PathType Leaf)) { throw "Agent introuvable : $AgentPath" }
    if (-not (Test-Path -LiteralPath $StatePath -PathType Leaf)) { throw "État Mesh introuvable : $StatePath" }
    if (-not (Test-Path -LiteralPath $HeadlessHostPath -PathType Leaf)) { throw 'Lanceur sans console introuvable. Exécutez Install ou Update.' }
    [void][System.Reflection.Assembly]::LoadFrom($HeadlessHostPath)

    $state = Get-Content -LiteralPath $StatePath -Raw -Encoding UTF8 | ConvertFrom-Json
    if (-not $state.nodeId -or -not $state.hubUrl -or -not $state.privateKey) {
        throw 'État Mesh incomplet ou non associé.'
    }

    # The persisted state remains authoritative. In particular, never retain an
    # enrollment code or override its hub during supervised restarts.
    $env:MESH_AGENT_STATE_PATH = $StatePath
    $env:MESH_HUB_URL = $null
    $env:MESH_ENROLLMENT_CODE = $null
    $env:MESH_NODE_ALIAS = [string]$state.alias
    $env:MESH_PROJECT_MODE = ${values.projectMode}
    $env:MESH_INCLUDE_TITLES = ${values.includeTitles}
    $env:NODE_DISABLE_COLORS = '1'
    Set-Location -LiteralPath $RepoRoot

    $launchAttempt = 0
    $restartAttempt = 0
    Write-SupervisorLog "supervisor started; statePath=$StatePath; restartDelaySeconds=$RestartDelaySeconds"
    while ($true) {
        # Stopping a scheduled supervisor can leave its child alive. Never start
        # another writer for the same state until that child has exited.
        $existingAgents = @(Get-CimInstance Win32_Process -ErrorAction Stop | Where-Object {
            $_.Name -ieq 'node.exe' -and $_.CommandLine -and
            $_.CommandLine.IndexOf($AgentPath, [System.StringComparison]::OrdinalIgnoreCase) -ge 0 -and
            $_.CommandLine.IndexOf($StatePath, [System.StringComparison]::OrdinalIgnoreCase) -ge 0
        })
        if ($existingAgents.Count -gt 0) {
            Write-SupervisorLog ("existing agent still running; launch deferred; pid=" + ($existingAgents.ProcessId -join ','))
            Start-Sleep -Seconds $RestartDelaySeconds
            continue
        }
        $launchAttempt += 1
        Write-SupervisorLog "agent launch; attempt=$launchAttempt"
        $exitCode = 1
        try {
            $global:LASTEXITCODE = 0
            $exitCode = Invoke-AgentProcess
        } catch {
            Write-SupervisorLog ("agent invocation failed: " + $_.Exception.Message)
            $exitCode = 1
        }

        Write-SupervisorLog "agent exited; exitCode=$exitCode"
        if ($exitCode -eq 0) {
            Write-SupervisorLog 'agent stopped normally; no automatic restart'
            break
        }

        $restartAttempt += 1
        Write-SupervisorLog "agent restart scheduled; restartAttempt=$restartAttempt; nextLaunchAttempt=$($launchAttempt + 1); delaySeconds=$RestartDelaySeconds"
        Start-Sleep -Seconds $RestartDelaySeconds
    }
} catch {
    Write-SupervisorLog ("supervisor failed: " + $_.Exception.Message)
    exit 1
} finally {
    if ($ownsMutex -and $mutex) { $mutex.ReleaseMutex() }
    if ($mutex) { $mutex.Dispose() }
}
`;
}

export async function writeWindowsSupervisor(filePath, options) {
  const normalizedPath = path.resolve(requireText(filePath, "filePath"));
  await mkdir(path.dirname(normalizedPath), { recursive: true });
  const content = generateWindowsSupervisor(options);
  await writeFile(normalizedPath, content, { encoding: "utf8", mode: 0o600 });
  return normalizedPath;
}

export async function preserveExistingAgentState({ sourcePath, destinationPath } = {}) {
  const destination = path.resolve(requireText(destinationPath, "destinationPath"));
  try {
    await access(destination);
    return { status: "existing", destinationPath: destination };
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  if (!sourcePath) return { status: "missing", destinationPath: destination };
  const source = path.resolve(sourcePath);
  try {
    await access(source);
  } catch (error) {
    if (error.code === "ENOENT") return { status: "missing", destinationPath: destination };
    throw error;
  }

  await mkdir(path.dirname(destination), { recursive: true });
  try {
    await copyFile(source, destination, fsConstants.COPYFILE_EXCL);
    return { status: "copied", sourcePath: source, destinationPath: destination };
  } catch (error) {
    if (error.code === "EEXIST") return { status: "existing", destinationPath: destination };
    throw error;
  }
}
